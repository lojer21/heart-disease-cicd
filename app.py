def _resolve_model_path() -> Path | None:
    env_path = os.environ.get("MODEL_PATH")
    app_dir = Path(__file__).resolve().parent
    candidates = [
        Path(env_path) if env_path else None,
        app_dir / "models" / "random_forest_model.pkl",
        app_dir / "models" / "heart_disease_model.pkl",
        app_dir / "random_forest_model.pkl",
        PROJECT_ROOT / "models" / "heart_disease_model.pkl",
        PROJECT_ROOT / "models" / "random_forest_model.pkl",
        PROJECT_ROOT / "random_forest_model.pkl",
        PROJECT_ROOT / "heart_pred" / "random_forest_model.pkl",
        Path("models/random_forest_model.pkl"),
        Path("models/heart_disease_model.pkl"),
        Path("random_forest_model.pkl"),
    ]
    for c in candidates:
        if c and c.exists() and c.is_file():
            return c.resolve()
    return None


@st.cache_resource(show_spinner=False)
def _load_bundle(path_str: str):
    obj = joblib.load(path_str)
    if isinstance(obj, dict) and "model" in obj:
        model = obj["model"]
        features = obj.get("features", DEFAULT_FEATURES)
        return model, list(features)
    # Standalone estimator (joblib.dump(rf, 'random_forest_model.pkl'))
    return obj, DEFAULT_FEATURES


def get_model():
    """Return (model, features, resolved_path, error_message). Never raises."""
    resolved = _resolve_model_path()
    if resolved is None:
        return None, None, None, (
            "Model file not found. Checked `models/heart_disease_model.pkl`, "
            "`models/random_forest_model.pkl`, and `random_forest_model.pkl`. "
            "Run training first or verify your model path."
        )
    try:
        model, features = _load_bundle(str(resolved))
        return model, features, str(resolved), None
    except Exception as exc:
        return None, None, str(resolved), f"The model could not be loaded: {exc}"


