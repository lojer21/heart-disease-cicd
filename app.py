def analyze_biomarkers(inputs: dict[str, Any]) -> list[dict[str, str]]:
    """Analyzes 13 clinical biomarkers against standard cardiology thresholds."""
    findings = []
    
    # Blood Pressure (AHA Guideline)
    bp = inputs.get("trestbps", 120)
    if bp >= 140:
        findings.append({"param": "Resting BP", "status": "danger", "note": f"{bp} mmHg (Stage 2 Hypertension)"})
    elif bp >= 130:
        findings.append({"param": "Resting BP", "status": "warn", "note": f"{bp} mmHg (Stage 1 Hypertension)"})
    else:
        findings.append({"param": "Resting BP", "status": "normal", "note": f"{bp} mmHg (Optimal/Normal)"})

    # Serum Cholesterol
    chol = inputs.get("chol", 200)
    if chol >= 240:
        findings.append({"param": "Cholesterol", "status": "danger", "note": f"{chol} mg/dL (High risk hyperlipidemia)"})
    elif chol >= 200:
        findings.append({"param": "Cholesterol", "status": "warn", "note": f"{chol} mg/dL (Borderline elevated)"})
    else:
        findings.append({"param": "Cholesterol", "status": "normal", "note": f"{chol} mg/dL (Desirable)"})

    # ST Depression (oldpeak)
    oldpeak = inputs.get("oldpeak", 0.0)
    if oldpeak >= 2.0:
        findings.append({"param": "ST Depression", "status": "danger", "note": f"{oldpeak} mm (Marked exercise-induced ischemia)"})
    elif oldpeak >= 1.0:
        findings.append({"param": "ST Depression", "status": "warn", "note": f"{oldpeak} mm (Moderate ST depression)"})
    else:
        findings.append({"param": "ST Depression", "status": "normal", "note": f"{oldpeak} mm (Normal baseline)"})

    # Exercise Induced Angina
    exang = inputs.get("exang", 0)
    if exang == 1:
        findings.append({"param": "Exercise Angina", "status": "danger", "note": "Positive (Coronary perfusion deficit)"})
    else:
        findings.append({"param": "Exercise Angina", "status": "normal", "note": "Negative"})

    # Max Heart Rate vs Expected Max (220 - age)
    age = inputs.get("age", 50)
    thalach = inputs.get("thalach", 150)
    expected_max = 220 - age
    pct_max = round((thalach / expected_max) * 100, 1) if expected_max > 0 else 100
    if pct_max < 75:
        findings.append({"param": "Heart Rate Reserve", "status": "warn", "note": f"{thalach} bpm ({pct_max}% of max - chronotropic insufficiency)"})
    else:
        findings.append({"param": "Heart Rate Reserve", "status": "normal", "note": f"{thalach} bpm ({pct_max}% achieved)"})

    # Major Vessels (Fluoroscopy ca)
    ca = inputs.get("ca", 0)
    if ca > 0:
        findings.append({"param": "Fluoroscopy Vessels", "status": "danger", "note": f"{ca} major vessel(s) flagged"})
    else:
        findings.append({"param": "Fluoroscopy Vessels", "status": "normal", "note": "0 vessels flagged"})

    return findings


def build_bedrock_prompt(result: dict[str, Any], findings: list[dict[str, str]]) -> str:
    pred = int(result["prediction"])
    prob = result["positive_probability"]
    inputs = result["inputs"]
    findings_str = "\n".join(f"- {f['param']}: {f['note']}" for f in findings)

    return f"""You are an expert cardiologist AI assistant on AWS Bedrock analyzing a machine learning heart disease risk evaluation.

PATIENT & MODEL ASSESSMENT:
- Model Prediction: Class {pred} ({'High Risk of Heart Disease' if pred == 1 else 'Low Risk / Normal Profile'})
- Model-Estimated Disease Probability: {prob:.2f}%
- Clinical Biomarkers Analyzed:
{findings_str}
- Demographics: Age {inputs.get('age')}, Sex {inputs.get('sex')} (1=Male, 0=Female)
- Chest Pain Type: Code {inputs.get('cp')}
- Fasting Blood Sugar > 120: {inputs.get('fbs')}
- Resting ECG: Code {inputs.get('restecg')}
- Slope of ST Segment: Code {inputs.get('slope')}
- Thalassemia: Code {inputs.get('thal')}

TASK:
Provide a structured, objective, and empathetic 3-part clinical summary:
1. CLINICAL SUMMARY: 2 to 3 sentences summarizing the machine learning risk output and overall risk severity.
2. KEY RISK DRIVERS: 3 concise bullet points identifying the specific biometric parameters (e.g. ST depression, cholesterol, vessels) that drive this outcome.
3. PREVENTATIVE RECOMMENDATIONS: 3 actionable lifestyle or clinical follow-up recommendations (e.g., lipid management, aerobic activity, diagnostic consultation).

Do not formulate a definitive diagnosis. Keep tone professional, evidence-based, and clear."""


def generate_bedrock_insights(
    result: dict[str, Any],
    model_id: str = DEFAULT_BEDROCK_MODEL_ID,
    region: str = DEFAULT_AWS_REGION
) -> dict[str, Any]:
    """Invokes Amazon Bedrock Runtime via boto3 with graceful intelligent clinical fallback."""
    findings = analyze_biomarkers(result["inputs"])
    prompt = build_bedrock_prompt(result, findings)
    
    # Try AWS Bedrock Runtime invocation
    try:
        import boto3
        bedrock = boto3.client("bedrock-runtime", region_name=region)

        if "anthropic.claude" in model_id:
            body = json.dumps({
                "anthropic_version": "bedrock-2023-05-31",
                "max_tokens": 600,
                "temperature": 0.2,
                "messages": [{"role": "user", "content": prompt}]
            })
        elif "amazon.titan" in model_id:
            body = json.dumps({
                "inputText": prompt,
                "textGenerationConfig": {
                    "maxTokenCount": 512,
                    "temperature": 0.2,
                    "topP": 0.9
                }
            })
        else:
            body = json.dumps({"prompt": prompt, "max_tokens": 500})

        response = bedrock.invoke_model(
            modelId=model_id,
            body=body,
            contentType="application/json",
            accept="application/json"
        )
        response_body = json.loads(response["body"].read().decode("utf-8"))

        if "content" in response_body and len(response_body["content"]) > 0:
            narrative = response_body["content"][0].get("text", "")
        elif "results" in response_body:
            narrative = response_body["results"][0].get("outputText", "")
        else:
            narrative = str(response_body)

        return {
            "narrative": narrative,
            "engine": f"Amazon Bedrock ({model_id})",
            "status": "online",
            "findings": findings,
            "disclaimer": DISCLAIMER,
        }

    except Exception as exc:
        # High quality clinical fallback
        pred = int(result["prediction"])
        prob = result["positive_probability"]
        high_risk_biomarkers = [f["note"] for f in findings if f["status"] in ("danger", "warn")]
        
        if pred == 1 or prob >= 50.0:
            summary = (
                f"The Random Forest model identified elevated cardiovascular risk indicators with a "
                f"model-estimated probability of {prob:.2f}%. This elevated score is correlated with notable "
                f"variations in cardiovascular stress metrics and diagnostic indicators."
            )
            drivers = high_risk_biomarkers[:3] if high_risk_biomarkers else [
                "Elevated resting blood pressure or borderline serum lipid concentration.",
                "ST-segment displacement during cardiovascular exertion tests.",
                "Reduced heart rate reserve during peak exercise stress."
            ]
            recommendations = [
                "Consult a cardiologist for a 12-lead diagnostic ECG and comprehensive echocardiogram evaluation.",
                "Discuss targeted lipid-lowering therapy and sodium-restricted dietary interventions.",
                "Initiate supervised, structured moderate aerobic exercise (e.g., 150 min/week brisk walking) post-physician clearance."
            ]
        else:
            summary = (
                f"The Random Forest model evaluated a low cardiovascular risk probability of {prob:.2f}%. "
                f"Key hemodynamic markers, exercise tolerance, and electrocardiographic baselines align "
                f"closely with standard reference thresholds."
            )
            drivers = [
                "Resting blood pressure and serum cholesterol within guideline-recommended ranges.",
                "Absence of exercise-induced angina or abnormal ST-segment depression during exertion.",
                "Favorable chronotropic response and unobstructed coronary fluoroscopy metrics."
            ]
            recommendations = [
                "Maintain heart-healthy Mediterranean or DASH-style nutritional habits.",
                "Continue regular moderate-to-vigorous cardiovascular conditioning exercises.",
                "Adhere to periodic annual preventative health and blood lipid profile screenings."
            ]

        fallback_narrative = (
            f"### 1. Clinical Summary\n{summary}\n\n"
            f"### 2. Key Biomarker Risk Drivers\n" + "\n".join(f"- {d}" for d in drivers) + "\n\n"
            f"### 3. Preventative & Follow-Up Recommendations\n" + "\n".join(f"- {r}" for r in recommendations)
        )

        return {
            "narrative": fallback_narrative,
            "engine": f"Clinical Intelligence Engine (Offline / Bedrock Fallback: {type(exc).__name__})",
            "status": "fallback",
            "findings": findings,
            "disclaimer": DISCLAIMER,
            "notice": f"AWS Bedrock note: {str(exc)}"
        }


