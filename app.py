def _render_result_body(result: dict) -> None:
    neg, pos = result["negative_probability"], result["positive_probability"]
    predicted = int(result["prediction"])
    label = "High Risk of Heart Disease" if predicted == 1 else "Low Risk of Heart Disease"
    banner_color = "#E53E3E" if predicted == 1 else "#38A169"

    st.markdown("### Prediction Result")
    left, right = st.columns([1, 1], gap="medium")
    with left:
        html(f"""
            <div class="result" style="border-left: 6px solid {banner_color};">
              <div class="lbl">Predicted Status</div>
              <div class="big">{label}</div>
              <div class="desc">The model classified this profile as <b>Class {predicted}</b> with 
              <b>{pos if predicted == 1 else neg:.2f}% confidence</b>.</div>
            </div>
        """)
        p0, p1 = st.columns(2, gap="small")
        with p0:
            html(f'<div class="prob c0"><div class="lbl">Class 0 (No Disease)</div><div class="val">{counter_html(neg, 2, "%")}</div>'
                 f'<div class="meter"><span style="--w:{neg:.2f}"></span></div></div>')
        with p1:
            html(f'<div class="prob c1"><div class="lbl">Class 1 (Heart Disease)</div><div class="val">{counter_html(pos, 2, "%")}</div>'
                 f'<div class="meter"><span style="--w:{pos:.2f}"></span></div></div>')
    with right:
        fig = go.Figure(go.Bar(
            x=["Class 0 (No Disease)", "Class 1 (Disease Risk)"], y=[neg, pos],
            marker=dict(color=[BLUE, TEAL], cornerradius=8) if hasattr(go.bar.Marker, "cornerradius") else dict(color=[BLUE, TEAL]),
            text=[f"{neg:.2f}%", f"{pos:.2f}%"], textposition="outside",
            hovertemplate="%{x}: %{y:.2f}%<extra></extra>", width=0.5,
        ))
        fig.update_yaxes(range=[0, 115], title="Model-estimated probability (%)", gridcolor="#E6EEF6", zeroline=False)
        fig.update_xaxes(showgrid=False)
        show_chart(style_figure(fig, 330), f"chart-v-prob-{st.session_state.get('run_id', 0)}")

    with st.expander("📋 Review Patient Diagnostic Input Values Sent to Model"):
        row = pd.DataFrame([result["inputs"]], columns=result["features"]).T
        row.columns = ["Submitted Value"]
        row.index.name = "Biomarker Feature"
        st.dataframe(row)

    # Render Amazon Bedrock GenAI Insights
    render_bedrock_insights_card(result)


def render_result(result: dict) -> None:
    with keyed_container(f"result-{st.session_state.get('run_id', 0)}"):
        _render_result_body(result)


def page_prediction(model, features, model_path, model_error) -> None:
    page_header(
        "Clinical AI Inference",
        "Heart Disease Risk Assessment",
        "Enter values for the 13 clinical biomarkers below to compute Random Forest risk probabilities "
        "and generate Amazon Bedrock Generative AI insights."
    )
    if model_error:
        st.error(model_error)
        disclaimer()
        return

    submitted = render_prediction_form()
    if submitted is not None:
        missing = [f for f in features if f not in submitted]
        extra = [k for k in submitted if k not in list(features)]
        if missing or extra:
            st.error(
                "The saved model's feature list does not match this form. "
                f"Missing from form: {missing or 'none'}. Not used by model: {extra or 'none'}."
            )
        else:
            loader = st.empty()
            loader.markdown("\n".join(l.strip() for l in loader_html().splitlines() if l.strip()),
                            unsafe_allow_html=True)
            try:
                if PREDICTION_DELAY_SECONDS:
                    time.sleep(PREDICTION_DELAY_SECONDS)
                st.session_state["result"] = run_prediction(model, features, submitted)
                st.session_state["run_id"] = st.session_state.get("run_id", 0) + 1
            except Exception as exc:
                st.session_state.pop("result", None)
                st.error(f"Prediction failed: {exc}")
            finally:
                loader.empty()

    if "result" in st.session_state:
        render_result(st.session_state["result"])
    disclaimer()


