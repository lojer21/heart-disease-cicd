def counter_html(value: float, decimals: int = 2, suffix: str = "") -> str:
    scaled = round(value * 10 ** decimals)
    whole, frac = divmod(scaled, 10 ** decimals)
    text = f"{value:.{decimals}f}{suffix}"
    if decimals == 0:
        visual = f'<span class="count int" aria-hidden="true" style="--i:{whole}">{whole}</span>'
    else:
        visual = f'<span class="count dec" aria-hidden="true" style="--i:{whole};--f:{frac}">{whole}.{frac:02d}</span>'
    return f'<span class="sr-only">{text}</span>{visual}<span aria-hidden="true">{suffix}</span>'


