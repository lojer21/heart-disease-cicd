def _ecg_path(beats: int = 2, width: int = 600, base_y: int = 30) -> str:
    step = width // beats
    d = f"M0 {base_y} "
    for i in range(beats):
        x0 = i * step
        d += (f"H{x0 + step * 0.23:.0f} q{step * 0.027:.0f} -10 {step * 0.053:.0f} 0 "
              f"H{x0 + step * 0.37:.0f} l6 6 l8 -28 l8 38 l6 -16 "
              f"H{x0 + step * 0.57:.0f} q{step * 0.04:.0f} -14 {step * 0.08:.0f} 0 H{x0 + step} ")
    return d.strip()


