    with left:
        st.markdown("#### Precision, Recall and F1-Score")
        metrics = ["Precision", "Recall", "F1-score"]
        fig = go.Figure()
        for (cls, vals), color in zip(CLASS_METRICS.items(), [BLUE, TEAL]):
            fig.add_trace(go.Bar(
                name=cls, x=metrics, y=[vals[m] for m in metrics], marker_color=color,
                text=[f"{vals[m]:.2f}" for m in metrics], textposition="outside",
                hovertemplate=f"{cls} · %{{x}}: %{{y:.2f}}<extra></extra>",
            ))
        fig.update_layout(barmode="group", legend=dict(orientation="h", y=1.12, x=0))
        fig.update_yaxes(range=[0, 1.15], gridcolor="#E6EEF6", zeroline=False)
        fig.update_xaxes(showgrid=False)
        show_chart(style_figure(fig, 340), "chart-v-metrics")
    with right:
        st.markdown("#### Confusion Matrix")
        z = CONFUSION_MATRIX
        fig = go.Figure(go.Heatmap(
            z=z, x=["Predicted 0", "Predicted 1"], y=["Actual 0", "Actual 1"],
            colorscale=[[0, "#EAF3FB"], [1, "#12335F"]], showscale=False, xgap=4, ygap=4,
            hovertemplate="%{y} / %{x}: %{z}<extra></extra>",
        ))
        peak = max(max(r) for r in z)
        for i, row in enumerate(z):
            for j, v in enumerate(row):
                fig.add_annotation(x=j, y=i, text=f"<b>{v}</b>", showarrow=False,
                                   font=dict(size=26, color="#FFFFFF" if v > peak * 0.5 else NAVY))
        fig.update_yaxes(autorange="reversed")
        show_chart(style_figure(fig, 340), "chart-x-confusion")

    st.markdown("#### Detailed Classification Report")
    report = pd.DataFrame(CLASS_METRICS).T
    report["Support"] = [tn + fp, fn + tp]
    st.dataframe(report.style.format({"Precision": "{:.2f}", "Recall": "{:.2f}", "F1-score": "{:.2f}"}))
    disclaimer()


